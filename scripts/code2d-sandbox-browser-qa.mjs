import {chromium} from 'playwright';
import {writeFile,mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('tmp/code2d-proof',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const report={route:'/motor-2d/codigo',engine:'Code2D new experimental',duration:40,autogeneratedByGemini:false,errors:[],providerRequests:0};
let page;
try{
 page=await browser.newPage({viewport:{width:480,height:900}});
 page.on('pageerror',e=>report.errors.push(e.message));
 page.on('request',r=>{if(/generativelanguage.googleapis.com|ai.gateway.lovable.dev/.test(r.url()))report.providerRequests++});
 await page.goto('http://127.0.0.1:4198/motor-2d/codigo',{waitUntil:'domcontentloaded'});
 await page.getByText('CrieSeuVideo — Estúdio de programação 2D').waitFor({timeout:30000});
 assert.equal(await page.locator('#code2d-mode').inputValue(),'team');
 const label=await page.locator('#code2d-duration').inputValue();
 assert.equal(label,'40');
 // ENGINE-only smoke input, not a model response and not a video offered to the user.
 const code=`function createScene(canvas,width,height){
   const ctx=canvas.getContext('2d');
   return {duration:40,renderAt(t){
    ctx.fillStyle='#162D5A';ctx.fillRect(0,0,width,height);
    ctx.fillStyle='#F5B428';ctx.beginPath();
    ctx.arc(width*(0.14+t/60),height*.49,45,0,Math.PI*2);ctx.fill();
   },dispose(){}};
 }`;
 const proof=await page.evaluate(async code=>{
   const {buildCode2DSandboxSrcdoc}=await import('/src/studio/code2d/sandbox.ts');
   const token='e'.repeat(32),nonce='f'.repeat(32);
   const srcdoc=buildCode2DSandboxSrcdoc({token,nonce,parentOrigin:location.origin,duration:40});
   const iframe=document.createElement('iframe');
   iframe.setAttribute('sandbox','allow-scripts');iframe.srcdoc=srcdoc;
   iframe.width='720';iframe.height='1280';iframe.style.display='none';
   const pending=new Map();
   let ready,fail;
   const connection=new Promise((resolve,reject)=>{ready=resolve;fail=reject;});
   window.addEventListener('message',e=>{
     if(e.source!==iframe.contentWindow||e.origin!=='null'||e.data?.token!==token)return;
     if(e.data.type==='boot'){
       iframe.contentWindow.postMessage({token,type:'init',width:720,height:1280,code},'*');
     }
     if(e.data.type==='ready')ready(e.data);
     if(e.data.type==='error')fail(new Error(e.data.stage+': '+e.data.message));
     if(e.data.type==='frame'){
       const done=pending.get(e.data.seq);pending.delete(e.data.seq);
       const c=document.createElement('canvas');c.width=720;c.height=1280;
       const x=c.getContext('2d');x.drawImage(e.data.bitmap,0,0);
       e.data.bitmap.close();
       done?.(x.getImageData(0,0,720,1280).data);
     }
   });
   document.body.appendChild(iframe);
   const info=await Promise.race([connection,new Promise((_,reject)=>setTimeout(()=>reject(new Error('boot timeout')),15000))]);
   const frame=async(t,seq)=>new Promise(resolve=>{
     pending.set(seq,resolve);
     iframe.contentWindow.postMessage({token,type:'frame',t,seq},'*');
   });
   const a=await frame(3,1),b=await frame(39,2),again=await frame(3,3);
   let difference=0,repeatDiff=0;
   for(let i=0;i<a.length;i+=16){
     if(a[i]!==b[i])difference++;
     if(a[i]!==again[i])repeatDiff++;
   }
   iframe.remove();
   return {duration:info.duration,replay:info.deterministic,difference,repeatDiff,codeLength:code.length};
 },code);
 report.sandbox=proof;
 assert.equal(proof.duration,40);
 assert.equal(proof.replay,true);
 assert.ok(proof.difference>0,'No movement across 40 seconds');
 assert.equal(proof.repeatDiff,0);
 assert.deepEqual(report.errors,[]);
 assert.equal(report.providerRequests,0);
 report.ok=true;
 console.log('CODE2D_40s_ISOLATED_CANVAS_PASS',JSON.stringify(proof));
}finally{
 await writeFile('tmp/code2d-proof/report.json',JSON.stringify(report,null,2));
 await page?.close().catch(()=>{});await browser.close();
}
