#!/usr/bin/env python3
"""Join ORIGINAL CrieSeuVideo Motion 2D native clips; synthesize a labeled TEST voice.
The visual composition is generated by src/studio/explainer/render.ts.
This script does not draw visuals or alter the app/production renderer.
"""
import json
import subprocess
from pathlib import Path

OUT = Path("tmp/motion2d-budget-40s")
BRIEF = Path("scripts/fixtures/motion2d-spending/brief.json")
brief = json.loads(BRIEF.read_text(encoding="utf-8"))
assert brief["duration"] == 40 and len(brief["scenes"]) == 8
OUT.mkdir(parents=True, exist_ok=True)

def cmd(*args):
    print("+", " ".join(map(str,args)),flush=True)
    subprocess.run([str(x) for x in args],check=True)

def probe(path):
    return json.loads(subprocess.check_output([
        "ffprobe","-v","error","-show_entries","format=duration",
        "-of","json",str(path)],text=True))["format"]["duration"]

def atempo_chain(ratio):
    # ffmpeg atempo stages each support 0.5 to 2.0.
    filters=[]
    while ratio > 2:
        filters.append("atempo=2.0")
        ratio/=2
    while ratio < .5:
        filters.append("atempo=0.5")
        ratio*=2
    filters.append(f"atempo={ratio:.8f}")
    return ",".join(filters)

voice_files=[]
for i,scene in enumerate(brief["scenes"]):
    raw=OUT/f"narration-raw-{i:02d}.wav"
    segment=OUT/f"narration-{i:02d}.wav"
    # eSpeak's pt-br voice is an offline TEST narrator, NOT ElevenLabs or final channel audio.
    cmd("espeak-ng","-v","pt-br","-s","158","-p","48","-a","145","-w",raw,scene["text"])
    raw_seconds=float(probe(raw))
    factor=raw_seconds/4.35
    filters=f"{atempo_chain(factor)},adelay=300,apad=pad_dur=5,atrim=duration=5"
    cmd("ffmpeg","-y","-hide_banner","-loglevel","error","-i",raw,
        "-af",filters,"-ac","1","-ar","48000","-c:a","pcm_s16le",segment)
    voice_files.append(segment)
    print("SCENE",i,"raw",raw_seconds,"stretch",factor,flush=True)

audio_list=OUT/"audio-concat.txt"
audio_list.write_text("".join(f"file '{f.name}'\n" for f in voice_files),encoding="utf-8")
audio=OUT/"narration-40s.wav"
cmd("ffmpeg","-y","-hide_banner","-loglevel","error","-f","concat","-safe","0",
    "-i",audio_list,"-ar","48000","-ac","1","-c:a","pcm_s16le",audio)

video_list=OUT/"video-concat.txt"
parts=[OUT/"motion2d-native-00s.mp4",OUT/"motion2d-native-20s.mp4"]
for p in parts: assert p.is_file() and p.stat().st_size > 10_000,p
video_list.write_text("".join(f"file '{p.name}'\n" for p in parts),encoding="utf-8")
silent=OUT/"motion2d-40s-sem-voz.mp4"
cmd("ffmpeg","-y","-hide_banner","-loglevel","error","-f","concat","-safe","0",
    "-i",video_list,"-c:v","copy","-an",silent)

final=OUT/"CrieSeuVideo_Motion2D_Gastos_Governo_40s_Legendado.mp4"
cmd("ffmpeg","-y","-hide_banner","-loglevel","error","-i",silent,"-i",audio,
    "-map","0:v:0","-map","1:a:0","-c:v","copy","-c:a","aac","-b:a","160k",
    "-af","loudnorm=I=-16:TP=-1.5:LRA=11","-t","40",
    "-movflags","+faststart",final)
data=json.loads(subprocess.check_output([
  "ffprobe","-v","error","-count_frames","-show_entries",
  "stream=codec_type,codec_name,width,height,nb_read_frames:format=duration",
  "-of","json",str(final)],text=True))
video=next(s for s in data["streams"] if s["codec_type"]=="video")
aud=next(s for s in data["streams"] if s["codec_type"]=="audio")
duration=float(data["format"]["duration"])
assert video["codec_name"]=="h264",video
assert video["width"]==720 and video["height"]==1280,video
assert int(video["nb_read_frames"])==1200,video
assert aud["codec_name"]=="aac",aud
assert abs(duration-40)<.1, duration
report={
  "renderer":"Actual CrieSeuVideo src/studio/explainer/render.ts (main)",
  "source":"Verified 2026 LOA budget, not executed spending",
  "authorship":"Manually selected scenes from real renderer primitives; no AI calls",
  "nativeRendererSegments":2,"nativeEncoderFramesPerSegment":600,
  "voice":"Offline eSpeak pt-br, demo only; approximate word sync; NOT ElevenLabs",
  "captions":"Native Motion 2D per-word captions from plan.ts and render.ts",
  "video":str(final),"probe":data,"seconds":duration,
  "limitations":"Motion 2D changes scene/reset at every 5s; captions use planned rather than actual speech alignment."
}
(OUT/"final-report.json").write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding="utf8")
print("FINAL_VIDEO",final,"DURATION",duration,"FRAMES",video["nb_read_frames"],flush=True)
